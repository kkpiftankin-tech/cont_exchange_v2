#pragma once
// Приведение глубины α кросс-пары к единицам номинала (ADR-064, дополнение 2026-10-29; OQ-F18v2-37). Чистая функция без ввода-вывода.
//
// Глубина α, которую строит agent_builder, измеряется в единицах котируемой валюты пары на ‰ (V_i = Σ price·size): у ETH/USDT это USDT на ‰, у ETH/BTC —
// BTC на ‰. Клиринг складывает потоки в узлах как стоимость в номинале (USDT) и считает по ним позицию агента и объём хеджа, поэтому α кросс-ребра, не
// приведённая к номиналу, занижает поток примерно в P0_quote раз (для BTC ≈ 8·10⁴). Поправка: α_value = α · P0_quote, где P0_quote — опорная цена
// котируемой валюты в номинале (константа окна, та же, что в reference_price = P0_base/P0_quote), а не цена узла: так функционал клиринга остаётся
// квадратичным. Для пар с котировкой в номинале множитель равен 1 (поведение не меняется).
// ВНИМАНИЕ: флаг включать нельзя без барьера или предела потока для кросс-рёбер (проба на dev 2026-10-29: поток ~200 тыс. USDT за такт, позиции до −10 млн USDT;
// ADR-064, дополнение; OQ-F18v2-38).

#include <cmath>
#include <string>

namespace cex::market_data::domain {

// Множитель глубины агента. enabled=false (флаг CE_CROSS_DEPTH_NUMERAIRE выключен) ⇒ 1, прежнее поведение побитно. Котировка в номинале ⇒ 1. Цена
// котируемой валюты не задана или не конечна ⇒ 1 (такую пару вызывающий код пропускает ещё раньше, как недостроимую без P0_quote; здесь — защита).
inline double CrossDepthNumeraireFactor(bool enabled, const std::string& quote, const std::string& numeraire, double p0_quote) {
  if (!enabled || quote.empty() || quote == numeraire) return 1.0;
  if (!std::isfinite(p0_quote) || p0_quote <= 0.0) return 1.0;
  return p0_quote;
}

}  // namespace cex::market_data::domain
