// ============================================================================
// trades_fetch_scheduler.hpp — справедливое REST-планирование чтения
// публичной ленты сделок (recent-trades) между символами ОДНОЙ venue.
//
// Назначение и физический смысл:
//   CexWsRestAdapter держит ОДИН rest_bucket_ (token bucket) на весь venue,
//   общий для snapshot/ticker/trades запросов ПО ВСЕМ символам этой биржи
//   (см. cpp/venues/src/infra/cex_ws_rest_adapter.cpp). poll_adapter в
//   venues_loop.cpp опрашивает символы адаптера последовательно в ФИКСИРОВАННОМ
//   порядке каждый такт — без приоритизации лента трейдов (запрашивается
//   последней, после snapshot+ticker) достаётся практически ВСЕГДА только
//   первому символу такта: бюджета (burst) не хватает на остальные 4+ пары.
//   Итог — хедж-заявки CE-агентов по "невыигравшим" стаканам EXPIRE
//   (none_cross/нет свежих публичных сделок для sim-матчинга, ADR-060).
//
//   Решение: перед каждым тактом снимаем "возраст" последнего успешного
//   чтения ленты для ВСЕХ символов адаптера и отдаём include_trades=true
//   только самому "голодному" (round-robin по голоду: как только он читает
//   трейды, его age обнуляется, и приоритет на следующем такте естественно
//   переходит к следующему по очереди символу). Остальные символы такта НЕ
//   тратят REST-токен на trades — экономия идёт именно победителю.
//
//   Чистая функция (без chrono/mutex/IO) — тестируема напрямую, не зависит
//   от CexWsRestAdapter.
// ============================================================================

#include <cstdint>
#include <string>
#include <vector>

namespace cex::venues::domain {

// Один символ + возраст (мс) последнего УСПЕШНОГО REST-чтения его ленты
// трейдов. age_ms < 0 означает "ещё не читали" — трактуется планировщиком
// как бесконечно устаревший (максимальный приоритет).
struct TradesFreshnessEntry {
  std::string venue_symbol;
  int64_t age_ms{-1};
};

// Возвращает true, если среди `candidate` + `others` (все символы ОДНОГО
// venue в текущем REST-такте) `candidate` — самый устаревший по чтению ленты
// трейдов и должен получить приоритет (include_trades=true) в этом такте.
// Тай-брейк при равном возрасте (включая случай "оба никогда не читались") —
// лексикографически МЕНЬШИЙ venue_symbol считается приоритетнее; это и
// только это обеспечивает детерминированную ротацию на самом первом такте,
// когда все символы ещё "никогда не читались" (иначе все получили бы
// include_trades=true одновременно и снова столкнулись бы за один
// rest_bucket_).
bool IsStalestTradesCandidate(const TradesFreshnessEntry& candidate,
                               const std::vector<TradesFreshnessEntry>& others);

// Режим планировщика опроса (ADR-078): лента сделок — отдельный запрос, и при фиксированном периоде 3 с чтение
// «у самой голодной пары в каждом тике» удваивало бы поток запросов (у Kraken бюджет 2 запр/с превышался, тики
// пропускались) и удлиняло снимок на ещё один последовательный запрос. Поэтому ленту пара читает не чаще раза в
// min_interval_ms; ещё не читавшаяся (age_ms < 0) — читает сразу.
bool TradesReadDue(int64_t age_ms, int64_t min_interval_ms);

}  // namespace cex::venues::domain
